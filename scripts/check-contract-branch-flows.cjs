const assert = require('node:assert/strict');
const path = require('node:path');
const { load, root } = require('./lib/load-typescript.cjs');

async function run() {
  const document = load(path.join(root, 'lib/management/contract-document'));
  const drafts = load(path.join(root, 'lib/management/contract-drafts'));
  const server = load(path.join(root, 'lib/server/contract-drafts'));
  const returns = load(path.join(root, 'lib/server/contract-returns'));
  const repository = load(path.join(root, 'lib/management/repository'));
  const checks = [];
  const dataset = { stores: [{ id: 1, name: 'CS nguồn khách QA' }, { id: 2, name: 'CS xe QA' }],
    staff: [{ id: 8, store_id: 2, name: 'Nhân viên xe QA', status: 'active' }],
    customers: [], vehicles: [{ id: 101, store_id: 2, name: 'Xe QA', license: '29B1-123.45' }], contracts: [] };
  const draft = document.createContractDraft(dataset, '2');
  draft.store_id = '1'; draft.staff_id = '8'; draft.payment_method = 'Tiền mặt'; draft.deposit_payment_method = 'Tiền mặt, CK tk công ty';
  draft.vehicles = [document.vehicleDetails(dataset.vehicles[0], draft.customer)];
  assert.deepEqual(drafts.validateDraftSave(draft, dataset), {});
  assert.deepEqual(drafts.validateDraftSave({ ...draft, vehicle_store_id: '1' }, dataset),{});
  assert.deepEqual(drafts.validateDraftSave({ ...draft, staff_id:'',staff_name:'Nhân viên hỗ trợ mới QA' }, dataset),{});
  const edits = { draft, status: 'draft', rental_type: 'daily', notes: 'QA' };
  assert.deepEqual(server.parseDraftEdits(edits), edits);
  for (const vehicle_store_id of [2, '1 OR 1=1', '-1', '9999999999999999999']) assert.throws(() => server.parseDraftEdits({ ...edits, draft: { ...draft, vehicle_store_id } }));
  const { vehicle_store_id, ...legacy } = draft;
  assert.equal(document.contractStaffStoreId(legacy), '1');
  assert.deepEqual(server.parseDraftEdits({ ...edits, draft: legacy }).draft, legacy);
  checks.push('supporting staff from other branches and typed new names are accepted; malformed branch IDs are rejected while old snapshots remain compatible');
  const row = { id: 901, code: 'QA-901', status: 'draft', draft_json: JSON.stringify(draft) };
  const reopened = document.createContractDraft(dataset, 'all', row);
  assert.equal(reopened.vehicle_store_id, '2'); assert.equal(reopened.store_id, '1'); assert.equal(reopened.staff_id, '8');
  assert.equal(reopened.payment_method, 'Tiền mặt'); assert.equal(reopened.deposit_payment_method, 'Tiền mặt, CK tk công ty');
  const collections = [{ purpose: 'rental', method: 'CK tk cá nhân', amount: 100000, paid_at: '2026-10-12T09:00', account: 'QA' }];
  const issued = document.createContractDraft(dataset, 'all', { ...row, status: 'renting', collections_json: JSON.stringify(collections) });
  assert.equal(issued.payment_method, 'CK tk cá nhân'); assert.equal(issued.deposit_payment_method, draft.deposit_payment_method);
  const oldRecord = document.createContractDraft(dataset, 'all', { id: 900, code: 'OLD-QA', status: 'renting', payment_method: 'Tiền mặt', deposit_payment_method: 'Tiền mặt' });
  assert.equal(oldRecord.payment_method, 'Tiền mặt'); assert.equal(oldRecord.deposit_payment_method, 'Tiền mặt');
  checks.push('draft reopen preserves both payment choices; old orders restore them and an uncollected deposit keeps its intended method');

  const pgIndex = process.argv.indexOf('--pglite-path');
  if (pgIndex !== -1) {
    const { PGlite } = require(path.resolve(process.argv[pgIndex + 1]));
    const db = new PGlite();
    const client = { query: async (sql, values) => { const result = await db.query(sql, values); return { ...result, rowCount: result.rows.length || result.affectedRows || 0 }; } };
    try {
      await db.exec(`CREATE SCHEMA himoto;
        CREATE TABLE himoto.stores(id bigint PRIMARY KEY, store_name text);
        CREATE TABLE himoto.customers(id bigint PRIMARY KEY,name text,phone text,id_card text,status text,address text,email text,
          id_card_issued_on date,id_card_issued_by text,driver_license_number text,driver_license_issued_on date,relatives jsonb,warning text);
        CREATE TABLE himoto.staff_profiles(id bigint PRIMARY KEY,store_id bigint,user_id bigint,full_name text);
        CREATE TABLE himoto.vehicles(id bigint PRIMARY KEY,name text,license text,current_store_id bigint,store_id bigint,brand text,type text,year int,color text);
        CREATE TABLE himoto.orders(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,store_id bigint,order_type text,order_status text,order_mode text,
          customer_id bigint,customer_name text,customer_phone text,customer_idnumber text,customer_address text,contract_number text,draft_reference text,
          rent_at timestamptz,return_at timestamptz,total numeric,total_rental_fees numeric,pid numeric,draft_payload jsonb,
          first_deposit_amount numeric,additional_deposit_amount numeric,note text,created_at timestamptz,updated_at timestamptz,deleted_at timestamptz,
          contract_responsible_user_id bigint,contract_signed_on date,contract_authorization_date date,contract_collateral_description text,customer_source text,customer_source_url text);
        CREATE TABLE himoto.order_vehicle_details(id bigint PRIMARY KEY,order_id bigint,vehicle_id bigint,rent_at timestamptz,return_at timestamptz,completed_at timestamptz,
          deleted_at timestamptz,type text,hiring_fee numeric,driver_name text,driver_license_number text,driver_license_issued_on date,borrow_hats int,borrow_raincoats int);
        CREATE TABLE himoto.transactions(id bigint PRIMARY KEY,order_id bigint,name text,type text,status text,value numeric,created_at timestamptz,
          bank_owner_type text,bank_id bigint,cash_id bigint);
        CREATE TABLE himoto.banks(id bigint PRIMARY KEY,bank_name text,owner_name text,account_number text);
        CREATE TABLE himoto.cash(id bigint PRIMARY KEY,name text);
        INSERT INTO himoto.stores VALUES(1,'CS nguồn khách QA'),(2,'CS xe QA');
        INSERT INTO himoto.staff_profiles VALUES(8,2,80,'Nhân viên xe QA');
        INSERT INTO himoto.vehicles(id,name,license,current_store_id,store_id) VALUES(101,'Xe QA','29B1-123.45',2,2);
        INSERT INTO himoto.customers(id,name,phone,id_card) VALUES(77,'Khách QA','090.000.0077','001234567877');`);
      draft.customer_id = 77;
      const saved = await server.saveDatabaseDraft(client, null, edits);
      const mapped = repository.mapApiRow('contracts', saved);
      const restored = document.createContractDraft(dataset, 'all', mapped);
      assert.equal(Number(saved.store_id), 1); assert.equal(Number(saved.staff_id), 8);
      assert.equal(restored.vehicle_store_id, '2'); assert.equal(restored.staff_id, '8');
      assert.equal(restored.payment_method, 'Tiền mặt'); assert.equal(restored.deposit_payment_method, draft.deposit_payment_method);
      assert.equal((await db.query('SELECT count(*)::int AS n FROM himoto.transactions')).rows[0].n, 0);
      const changed = await server.saveDatabaseDraft(client, Number(saved.id), { ...edits, revision: saved.draft_revision, draft: { ...restored, payment_method: 'CK tk công ty' } });
      assert.equal(changed.draft_payload.management_composer.draft.payment_method, 'CK tk công ty');
      assert.equal(changed.draft_payload.management_composer.draft.vehicle_store_id, '2');
      checks.push('in-memory PostgreSQL executes actual draft save/update/list SQL, retaining vehicle branch, staff and payment choices without receipts');
      await db.exec(`UPDATE himoto.orders SET order_status='renting',contract_number='HD-QA-901',customer_idnumber='001234567877',customer_phone='0900000077' WHERE id=${Number(saved.id)};
        INSERT INTO himoto.order_vehicle_details(id,order_id,vehicle_id,rent_at,return_at,type,hiring_fee) VALUES(201,${Number(saved.id)},101,now(),now()+interval '1 day','day',200000);`);
      for (const query of ['HD-QA-901', '001234567877', '0900000077', '090 000 0077', '29B1-123.45', '29b1 12345', '12345']) {
        assert.deepEqual((await returns.searchReturnableItems(client, query)).map(row => row.item_id), [201], query);
      }
      for (const query of ['', '999999999999', 'NO-MATCH', "%' OR 1=1 --", '_']) assert.equal((await returns.searchReturnableItems(client, query)).length, 0, query);
      await db.exec('UPDATE himoto.customers SET phone=NULL WHERE id=77;');
      assert.equal((await returns.searchReturnableItems(client, '0900000077')).length, 1);
      checks.push('actual PostgreSQL return lookup finds contract, CCCD, formatted phone and plates with/without punctuation; legacy phone fallback and escaped wildcards work');
    } finally { await db.close(); }
  }
  console.log(JSON.stringify({ passed: checks.length, checks, realDatabaseAccess: false }, null, 2));
}
run().catch(error => { console.error(error.stack); process.exitCode = 1; });
