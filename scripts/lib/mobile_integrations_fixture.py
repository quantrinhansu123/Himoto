            rows=[r for r in rows if(not q.get('status')or r['status']==q['status'])and search in(r['code']+r['name']+r['license']+r['phone']).lower()];size=int(q.get('size',20));page=int(q.get('page',1));pages=max(1,math.ceil(len(rows)/size));page=min(page,pages);return 200,{'rows':rows[(page-1)*size:page*size],'total':len(rows),'page':page,'pages':pages,'statusCounts':[],'updatedAt':datetime.now(timezone.utc).isoformat(),'scope':scope},False
