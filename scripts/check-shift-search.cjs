const assert = require('node:assert/strict');
const path = require('node:path');
const { load } = require('./check-contract-payments.cjs');
const { searchRegistrationShifts, SHIFT_SEARCH_OPTIONS } = load(path.resolve('src/lib/management/shift-search'));
const codes = query => searchRegistrationShifts(query).map(shift => shift.code);
assert.equal(SHIFT_SEARCH_OPTIONS.length, 9);
assert.deepEqual(codes(''), SHIFT_SEARCH_OPTIONS.map(shift => shift.code));
assert.deepEqual(codes('  '), codes(''));
assert(codes('sáng').includes('G1'));
assert.deepEqual(codes('sang'), codes('sáng'));
assert.deepEqual(codes('TỐI'), codes('toi'));
assert(codes('G1').includes('G1'));
assert.deepEqual(codes('g1+g3'), ['G1+G3']);
assert.deepEqual(codes('nghi'), ['O']);
assert(codes('08:00').includes('S'));
assert(codes('8h').includes('G1'));
assert(codes('08h').includes('G1'));
assert(codes('17:00').includes('G3'));
assert.deepEqual(codes('ca sang 12:00'), ['G1', 'G1+G3']);
assert.deepEqual(codes('không có mã này'), []);
assert.deepEqual(codes('chua dang ky'), ['']);
assert.equal(SHIFT_SEARCH_OPTIONS.find(shift => shift.code === 'G1+G3').hours, '08:00–12:00 · 17:00–21:00');
console.log('PASS: all 9 choices, accent/case-insensitive code/name/hour search, hour aliases, multiword queries, empty results, clear selection and split-shift hours');
