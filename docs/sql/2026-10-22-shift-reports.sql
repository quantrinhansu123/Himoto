BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE IF NOT EXISTS himoto.management_shift_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id bigint NOT NULL REFERENCES himoto.stores(id),
  report_date date NOT NULL,
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','submitted')),
  revision integer NOT NULL DEFAULT 1,
  created_by bigint NOT NULL REFERENCES himoto.users(id),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(store_id,report_date)
);
CREATE TABLE IF NOT EXISTS himoto.management_shift_photos (
  report_id bigint NOT NULL REFERENCES himoto.management_shift_reports(id),
  store_id bigint NOT NULL REFERENCES himoto.stores(id),
  slot text NOT NULL CHECK (slot IN ('vehicles','batteries','cash','personal','company','door')),
  mime_type text NOT NULL,
  data bytea NOT NULL CHECK (octet_length(data) BETWEEN 1 AND 2097152),
  PRIMARY KEY(report_id,slot)
);
ALTER TABLE himoto.management_shift_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE himoto.management_shift_photos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS shift_scope ON himoto.management_shift_reports;
CREATE POLICY shift_scope ON himoto.management_shift_reports TO himoto_scoped
  USING (current_setting('himoto.scope_all',true)='true' OR store_id=NULLIF(current_setting('himoto.store_id',true),'')::bigint)
  WITH CHECK (current_setting('himoto.scope_all',true)='true' OR store_id=NULLIF(current_setting('himoto.store_id',true),'')::bigint);
DROP POLICY IF EXISTS shift_photo_scope ON himoto.management_shift_photos;
CREATE POLICY shift_photo_scope ON himoto.management_shift_photos TO himoto_scoped
  USING (current_setting('himoto.scope_all',true)='true' OR store_id=NULLIF(current_setting('himoto.store_id',true),'')::bigint)
  WITH CHECK (current_setting('himoto.scope_all',true)='true' OR store_id=NULLIF(current_setting('himoto.store_id',true),'')::bigint);
GRANT SELECT,INSERT,UPDATE ON himoto.management_shift_reports,himoto.management_shift_photos TO himoto_scoped;
GRANT USAGE,SELECT ON SEQUENCE himoto.management_shift_reports_id_seq TO himoto_scoped;
COMMIT;
