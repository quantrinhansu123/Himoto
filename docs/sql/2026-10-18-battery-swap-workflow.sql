BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE IF NOT EXISTS himoto.management_contract_battery_swaps(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES himoto.orders(id),item_id bigint NOT NULL REFERENCES himoto.order_vehicle_details(id),
  vehicle_id bigint NOT NULL REFERENCES himoto.vehicles(id),request_id uuid NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'draft' CHECK(status IN('draft','confirmed')),
  battery_percent integer CHECK(battery_percent BETWEEN 0 AND 100),fee bigint NOT NULL DEFAULT 0 CHECK(fee IN(0,100000)),
  note text NOT NULL DEFAULT '',created_by bigint NOT NULL REFERENCES himoto.users(id),confirmed_by bigint REFERENCES himoto.users(id),
  transaction_id bigint REFERENCES himoto.transactions(id) ON DELETE SET NULL,confirmation_hash text,
  created_at timestamptz NOT NULL DEFAULT now(),confirmed_at timestamptz
);
CREATE INDEX IF NOT EXISTS management_contract_battery_swaps_order_idx ON himoto.management_contract_battery_swaps(order_id,id);
ALTER TABLE himoto.management_contract_battery_swaps ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON himoto.management_contract_battery_swaps FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE ON himoto.management_contract_battery_swaps TO himoto_scoped;
GRANT USAGE,SELECT ON SEQUENCE himoto.management_contract_battery_swaps_id_seq TO himoto_scoped;
DROP POLICY IF EXISTS battery_swap_scope ON himoto.management_contract_battery_swaps;
CREATE POLICY battery_swap_scope ON himoto.management_contract_battery_swaps TO himoto_scoped
  USING(EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id AND o.deleted_at IS NULL))
  WITH CHECK(EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id AND o.deleted_at IS NULL));
ALTER TABLE himoto.management_record_photos DROP CONSTRAINT IF EXISTS management_record_photos_slots;
ALTER TABLE himoto.management_record_photos ADD CONSTRAINT management_record_photos_slots CHECK(
 (entity_type='customers' AND slot IN('id_front','id_back','driver_license')) OR
 (entity_type='contracts' AND (slot IN('driver-license','customer-id-front','customer-id-back','customer-driver-license') OR slot ~ '^plate-[1-9][0-9]{0,14}$' OR slot ~ '^(rental|handover)-([1-9]|1[0-5]|video-[1-3]|document-([1-9]|1[0-5]))$' OR slot ~ '^(return|renewal|renewal-receipt)-[1-9][0-9]{0,14}-([1-9]|1[0-5]|video-[1-3]|document-([1-9]|1[0-5]))$' OR slot ~ '^battery-swap-[1-9][0-9]{0,14}-([12]|video-1|document-([1-9]|1[0-5]))$'))
);
ALTER TABLE himoto.management_contract_notifications DROP CONSTRAINT IF EXISTS management_contract_notifications_event_type_check;
ALTER TABLE himoto.management_contract_notifications ADD CONSTRAINT management_contract_notifications_event_type_check CHECK(event_type IN('rental','reservation','handover','return','renewal','battery_swap'));
COMMIT;
