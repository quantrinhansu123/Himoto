BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE IF NOT EXISTS himoto.management_collection_followups (
  order_id bigint PRIMARY KEY REFERENCES himoto.orders(id),
  store_id bigint NOT NULL REFERENCES himoto.stores(id),
  contact_status text NOT NULL CHECK(contact_status IN ('uncontacted','contacted','unreachable','promised')),
  handling_status text NOT NULL CHECK(handling_status IN ('branch','escalated','resolved')),
  customer_condition text NOT NULL DEFAULT '' CHECK(length(customer_condition)<=300),
  notes text NOT NULL DEFAULT '' CHECK(length(notes)<=3000),
  revision integer NOT NULL DEFAULT 1,
  updated_by bigint NOT NULL REFERENCES himoto.users(id),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS himoto.management_collection_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES himoto.orders(id),
  store_id bigint NOT NULL REFERENCES himoto.stores(id),
  snapshot jsonb NOT NULL,
  updated_by bigint NOT NULL REFERENCES himoto.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS himoto.management_report_deliveries (
  delivery_key text PRIMARY KEY,
  store_id bigint NOT NULL REFERENCES himoto.stores(id),
  route text NOT NULL CHECK(route IN ('store','ownership_new')),
  text text NOT NULL CHECK(length(text) BETWEEN 1 AND 4000),
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sending','sent','failed','unknown','awaiting_config')),
  message_id bigint,
  error_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE himoto.management_collection_followups ENABLE ROW LEVEL SECURITY;
ALTER TABLE himoto.management_collection_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE himoto.management_report_deliveries ENABLE ROW LEVEL SECURITY;
DO $$DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['management_collection_followups','management_collection_history','management_report_deliveries'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS operating_report_scope ON himoto.%I',t);
    EXECUTE format('CREATE POLICY operating_report_scope ON himoto.%I TO himoto_scoped USING (current_setting(''himoto.scope_all'',true)=''true'' OR store_id=NULLIF(current_setting(''himoto.store_id'',true),'''')::bigint) WITH CHECK (current_setting(''himoto.scope_all'',true)=''true'' OR store_id=NULLIF(current_setting(''himoto.store_id'',true),'''')::bigint)',t);
  END LOOP;
END $$;
GRANT SELECT,INSERT,UPDATE ON himoto.management_collection_followups,himoto.management_report_deliveries TO himoto_scoped;
GRANT SELECT,INSERT ON himoto.management_collection_history TO himoto_scoped;
GRANT USAGE,SELECT ON SEQUENCE himoto.management_collection_history_id_seq TO himoto_scoped;
COMMIT;
