BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE IF NOT EXISTS himoto.management_sepay_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id text NOT NULL, mode text NOT NULL CHECK(mode IN ('test','live')),
  fingerprint text NOT NULL, transfer_type text NOT NULL CHECK(transfer_type IN ('in','out')),
  amount bigint NOT NULL CHECK(amount>0), account_number text NOT NULL, content text NOT NULL,
  reference_code text NOT NULL DEFAULT '', transaction_at timestamptz NOT NULL, received_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL CHECK(status IN ('received','matched','simulated','unmatched','review','ignored')),
  order_id bigint REFERENCES himoto.orders(id), store_id bigint REFERENCES himoto.stores(id),
  transaction_id bigint REFERENCES himoto.transactions(id), message text NOT NULL DEFAULT '',
  UNIQUE(mode,external_id)
);
CREATE INDEX IF NOT EXISTS management_sepay_events_order_idx ON himoto.management_sepay_events(order_id,id DESC);
ALTER TABLE himoto.management_sepay_events ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON himoto.management_sepay_events TO himoto_scoped;
DROP POLICY IF EXISTS management_sepay_gate ON himoto.management_sepay_events;
CREATE POLICY management_sepay_gate ON himoto.management_sepay_events FOR SELECT TO himoto_scoped USING(true);
DROP POLICY IF EXISTS management_sepay_scope ON himoto.management_sepay_events;
CREATE POLICY management_sepay_scope ON himoto.management_sepay_events AS RESTRICTIVE FOR SELECT TO himoto_scoped USING(himoto.access_store(store_id));
COMMIT;
