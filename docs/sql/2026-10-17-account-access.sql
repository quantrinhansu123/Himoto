BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE IF NOT EXISTS himoto.management_account_access (
  user_id bigint PRIMARY KEY REFERENCES himoto.users(id), login_name varchar(100) NOT NULL UNIQUE,
  access_role varchar(40) NOT NULL CHECK(access_role IN ('branch_staff','ownership_staff','ownership_manager','hr','accounting','admin')),
  store_id bigint REFERENCES himoto.stores(id), scope_all boolean NOT NULL DEFAULT false,
  permissions jsonb NOT NULL DEFAULT '[]', enabled boolean NOT NULL DEFAULT true,
  created_by bigint REFERENCES himoto.users(id), updated_by bigint REFERENCES himoto.users(id),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK(scope_all OR store_id IS NOT NULL), CHECK(jsonb_typeof(permissions)='array'),
  CHECK(access_role NOT IN ('branch_staff','ownership_staff','ownership_manager') OR (NOT scope_all AND store_id IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS himoto.management_access_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id bigint NOT NULL REFERENCES himoto.users(id),
  target_user_id bigint NOT NULL REFERENCES himoto.users(id), action text NOT NULL,
  before_value jsonb, after_value jsonb, created_at timestamptz NOT NULL DEFAULT now()
);
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='himoto_scoped') THEN CREATE ROLE himoto_scoped NOLOGIN NOINHERIT; END IF;
END $$;
GRANT himoto_scoped TO postgres;
GRANT USAGE ON SCHEMA himoto TO himoto_scoped;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA himoto TO himoto_scoped;
CREATE OR REPLACE FUNCTION himoto.access_store(target numeric) RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT current_setting('himoto.scope_all',true)='true' OR target=NULLIF(current_setting('himoto.store_id',true),'')::bigint
$$;
CREATE OR REPLACE FUNCTION himoto.access_operation() RETURNS text LANGUAGE sql STABLE AS $$ SELECT COALESCE(current_setting('himoto.operation',true),'') $$;
CREATE OR REPLACE FUNCTION himoto.access_actor() RETURNS bigint LANGUAGE sql STABLE AS $$ SELECT NULLIF(current_setting('himoto.actor_id',true),'')::bigint $$;
CREATE OR REPLACE FUNCTION himoto.store_directory() RETURNS TABLE(id bigint,store_name varchar) LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,himoto AS $$
  SELECT id,store_name FROM himoto.stores WHERE status='opening' ORDER BY id
$$;
REVOKE ALL ON FUNCTION himoto.store_directory() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION himoto.store_directory() TO himoto_scoped;
CREATE OR REPLACE FUNCTION himoto.vehicle_has_open_rental(target bigint) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,himoto AS $$
  SELECT EXISTS(SELECT 1 FROM himoto.order_vehicle_details d JOIN himoto.orders o ON o.id=d.order_id
    WHERE d.vehicle_id=target AND d.deleted_at IS NULL AND d.completed_at IS NULL AND o.deleted_at IS NULL
      AND o.order_status IN ('renting','overdue','wait_payment','pending','deposit_contract'))
$$;
REVOKE ALL ON FUNCTION himoto.vehicle_has_open_rental(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION himoto.vehicle_has_open_rental(bigint) TO himoto_scoped;
CREATE OR REPLACE FUNCTION himoto.vehicle_has_other_rental(target bigint,excluded_order bigint) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,himoto AS $$
  SELECT EXISTS(SELECT 1 FROM himoto.order_vehicle_details d JOIN himoto.orders o ON o.id=d.order_id
    WHERE d.vehicle_id=target AND d.order_id IS DISTINCT FROM excluded_order AND d.deleted_at IS NULL AND d.completed_at IS NULL AND o.deleted_at IS NULL
      AND o.order_status IN ('renting','overdue','wait_payment','pending','deposit_contract'))
$$;
REVOKE ALL ON FUNCTION himoto.vehicle_has_other_rental(bigint,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION himoto.vehicle_has_other_rental(bigint,bigint) TO himoto_scoped;
CREATE OR REPLACE FUNCTION himoto.contract_day_last(day text) RETURNS integer LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,himoto AS $$
  SELECT COALESCE(max(substring(contract_number from 8)::int),0) FROM himoto.orders WHERE day ~ '^[0-9]{6}$' AND contract_number ~ ('^'||day||'-[0-9]{4}$')
$$;
REVOKE ALL ON FUNCTION himoto.contract_day_last(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION himoto.contract_day_last(text) TO himoto_scoped;
DO $$
DECLARE item record; read_rule text; write_rule text;
BEGIN
  FOR item IN SELECT * FROM (VALUES
    ('stores','himoto.access_store(id) OR himoto.access_operation() IN (''transfer'',''receive'')','false'),
    ('customers','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('staff_profiles','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('store_duty_schedules','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('orders','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('vehicles','himoto.access_store(COALESCE(current_store_id,store_id)) OR (himoto.access_operation()=''transfer'' AND status=''in_transit'' AND id=NULLIF(current_setting(''himoto.transfer_vehicle_id'',true),'''')::bigint)','himoto.access_store(COALESCE(current_store_id,store_id)) OR himoto.access_operation()=''transfer'''),
    ('battery_contracts','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('banks','himoto.access_store(store_id) OR (owner_type=''company'' AND COALESCE(store_id,0)=0)','himoto.access_store(store_id)'),
    ('cash','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('transactions','himoto.access_store(store_id)','himoto.access_store(store_id)'),
    ('order_vehicle_details','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id) AND EXISTS(SELECT 1 FROM himoto.vehicles v WHERE v.id=vehicle_id)'),
    ('activity_logs','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)'),
    ('management_contract_payments','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)'),
    ('management_contract_vehicle_swaps','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)','EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=order_id)'),
    ('management_record_photos','(entity_type=''customers'' AND EXISTS(SELECT 1 FROM himoto.customers c WHERE c.id=entity_id)) OR (entity_type=''contracts'' AND EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=entity_id))','(entity_type=''customers'' AND EXISTS(SELECT 1 FROM himoto.customers c WHERE c.id=entity_id)) OR (entity_type=''contracts'' AND EXISTS(SELECT 1 FROM himoto.orders o WHERE o.id=entity_id))'),
    ('gps_devices','EXISTS(SELECT 1 FROM himoto.vehicles v WHERE v.id=vehicle_id)','false'),
