    ('management_contract_types','true','false'),
    ('roles','true','false')
  ) AS policy(table_name,read_expression,write_expression)
  LOOP
    IF to_regclass('himoto.'||item.table_name) IS NULL THEN CONTINUE; END IF;
    EXECUTE format('ALTER TABLE himoto.%I ENABLE ROW LEVEL SECURITY',item.table_name);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON himoto.%I TO himoto_scoped',item.table_name);
    EXECUTE format('DROP POLICY IF EXISTS management_scoped_gate ON himoto.%I',item.table_name);
    EXECUTE format('CREATE POLICY management_scoped_gate ON himoto.%I FOR ALL TO himoto_scoped USING (true) WITH CHECK (true)',item.table_name);
    EXECUTE format('DROP POLICY IF EXISTS management_scoped_read ON himoto.%I',item.table_name);
    EXECUTE format('CREATE POLICY management_scoped_read ON himoto.%I AS RESTRICTIVE FOR SELECT TO himoto_scoped USING (%s)',item.table_name,item.read_expression);
    EXECUTE format('DROP POLICY IF EXISTS management_scoped_insert ON himoto.%I',item.table_name);
    EXECUTE format('CREATE POLICY management_scoped_insert ON himoto.%I AS RESTRICTIVE FOR INSERT TO himoto_scoped WITH CHECK (%s)',item.table_name,item.write_expression);
    EXECUTE format('DROP POLICY IF EXISTS management_scoped_update ON himoto.%I',item.table_name);
    EXECUTE format('CREATE POLICY management_scoped_update ON himoto.%I AS RESTRICTIVE FOR UPDATE TO himoto_scoped USING (%s) WITH CHECK (%s)',item.table_name,item.read_expression,item.write_expression);
    EXECUTE format('DROP POLICY IF EXISTS management_scoped_delete ON himoto.%I',item.table_name);
    EXECUTE format('CREATE POLICY management_scoped_delete ON himoto.%I AS RESTRICTIVE FOR DELETE TO himoto_scoped USING (%s)',item.table_name,item.write_expression);
  END LOOP;
END $$;
ALTER TABLE himoto.users ENABLE ROW LEVEL SECURITY;
GRANT SELECT(id,name,email,status,role,role_id,store_id,deleted_at) ON himoto.users TO himoto_scoped;
DROP POLICY IF EXISTS management_scoped_user_names ON himoto.users;
DROP POLICY IF EXISTS management_scoped_gate ON himoto.users;
CREATE POLICY management_scoped_gate ON himoto.users FOR SELECT TO himoto_scoped USING (true);
CREATE POLICY management_scoped_user_names ON himoto.users AS RESTRICTIVE FOR SELECT TO himoto_scoped USING (
  current_setting('himoto.scope_all',true)='true' OR id=himoto.access_actor() OR EXISTS(SELECT 1 FROM himoto.staff_profiles p WHERE p.user_id=users.id)
);
